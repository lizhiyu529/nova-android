/** 配色预览用的三色小样。 */
data class PalettePreview(
    val background: Color,
    val card: Color,
    val accent: Color,
)

enum class PaletteScheme(val label: String) {
    NeutralGray("中性灰"),
    NeutralBlack("中性黑"),
    SilverGray("银灰"),
    Caramel("焦糖"),
    Pudding("布丁"),
}

